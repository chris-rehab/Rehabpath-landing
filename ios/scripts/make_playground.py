#!/usr/bin/env python3
"""Builds a Swift Playgrounds app package (RehabPath.swiftpm) from the iOS sources.

Swift Playgrounds on iPad opens a self-contained .swiftpm folder and runs it with no Mac, Xcode or
Apple Developer account. The package can't reference RehabPathCore by path, so this script merges
the Core and app sources into one module, copies the asset catalog, and writes the manifest.

The demo build uses the synthetic sample data in memory: it opens straight onto Today, nothing is
saved, no notification prompt appears, and "Delete all my data" on the Privacy tab returns to
onboarding.

Usage: python3 ios/scripts/make_playground.py [output-dir]    (default: ios/build/RehabPath.swiftpm)
"""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

IOS = Path(__file__).resolve().parent.parent
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else IOS / "build" / "RehabPath.swiftpm"

CORE_SOURCES = IOS / "Packages" / "RehabPathCore" / "Sources" / "RehabPathCore"
APP_SOURCES = IOS / "RehabPath"
ASSETS = APP_SOURCES / "Resources" / "Assets.xcassets"

DEMO_LAUNCH_OLD = "arguments: [String] = ProcessInfo.processInfo.arguments"
DEMO_LAUNCH_NEW = 'arguments: [String] = ["-ui-testing", "-seed-onboarded"]'

MANIFEST = """// swift-tools-version: 5.9

// Generated by ios/scripts/make_playground.py from the RehabPath iOS sources. Do not edit by hand.

import PackageDescription
import AppleProductTypes

let package = Package(
    name: "RehabPath",
    platforms: [
        .iOS("17.0")
    ],
    products: [
        .iOSApplication(
            name: "RehabPath",
            targets: ["AppModule"],
            bundleIdentifier: "nz.co.rehabpath.playground",
            teamIdentifier: "",
            displayVersion: "0.1",
            bundleVersion: "1",
            appIcon: .asset("AppIcon"),
            accentColor: .asset("AccentColor"),
            supportedDeviceFamilies: [
                .pad,
                .phone
            ],
            supportedInterfaceOrientations: [
                .portrait,
                .landscapeRight,
                .landscapeLeft,
                .portraitUpsideDown(.when(deviceFamilies: [.pad]))
            ]
        )
    ],
    targets: [
        .executableTarget(
            name: "AppModule",
            path: "."
        )
    ]
)
"""


def copy_sources(source_root: Path, destination: Path) -> int:
    count = 0
    for path in sorted(source_root.rglob("*.swift")):
        text = path.read_text(encoding="utf-8")
        text = "\n".join(line for line in text.split("\n") if line.strip() != "import RehabPathCore")
        if path.name == "RehabPathApp.swift":
            assert DEMO_LAUNCH_OLD in text, "launch-argument default changed; update make_playground.py"
            text = text.replace(DEMO_LAUNCH_OLD, DEMO_LAUNCH_NEW)
        target = destination / path.relative_to(source_root)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        count += 1
    return count


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    core = copy_sources(CORE_SOURCES, OUT / "Core")
    app = copy_sources(APP_SOURCES, OUT / "App")
    shutil.copytree(ASSETS, OUT / "Assets.xcassets")
    (OUT / "Package.swift").write_text(MANIFEST, encoding="utf-8")
    print(f"Wrote {OUT} ({core} core + {app} app Swift files)")


if __name__ == "__main__":
    main()
